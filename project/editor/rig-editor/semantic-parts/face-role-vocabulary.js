/**
 * Every role a piece of artwork can play, in one list.
 *
 * ```text
 *   IMG_2043.png  →  What is it?  [ Left ear  ▾ ]  →  semanticParts.ears.roles.leftEar
 * ```
 *
 * The checklist in `face-roles.js` is the **eight** a beginner is walked
 * through, and it says so. The registry knows twenty-five, and for a long
 * time the other seventeen were reachable only from *Rig ▸ Deform ▸ All
 * parts* — an advanced screen, inside a collapsed section, behind a
 * *+ Add Part* menu. So importing `cheveux.png` or `ear-left.png` left an
 * author looking for somewhere to say what the file was, and there was
 * nowhere: hair, ears, a nose, a jaw, a tongue, teeth and the eyelids had no
 * row anywhere.
 *
 * This is the whole vocabulary, derived from `SEMANTIC_PART_REGISTRY` rather
 * than written out again, so a part added to the registry is assignable the
 * day it exists. Three surfaces read it: the Inspector's *What it is*, the
 * checklist's optional group, and the reading of a dropped file's name.
 *
 * Pure data and derivation. Nothing here writes to a document.
 */
import { SEMANTIC_PART_REGISTRY, requiredSemanticRoles } from './part-registry.js';

/**
 * What each role is called, and what it is for, in the author's words.
 *
 * Written out rather than derived from the role id: `leftUpper` is "left upper
 * eyelid" to a person and `hairBack` is "hair behind the head", and a label
 * generated by splitting camel case would say neither. A role missing from
 * here still appears — under its own id, which is worse than a sentence and
 * much better than being unassignable.
 */
const ROLE_WORDS = Object.freeze({
  head: ['Head', 'The whole face or head shape.'],
  leftEye: ['Left eye', 'The eye on the left of the canvas.'],
  rightEye: ['Right eye', 'The eye on the right of the canvas.'],
  leftPupil: ['Left pupil', 'Inside the left eye. It moves when the mascot looks around.'],
  rightPupil: ['Right pupil', 'Inside the right eye.'],
  leftIris: ['Left iris', 'The ring of colour the left pupil sits in. It travels with the pupil.'],
  rightIris: ['Right iris', 'The ring of colour the right pupil sits in.'],
  leftUpper: ['Left upper eyelid', 'Comes down to close the left eye.'],
  leftLower: ['Left lower eyelid', 'Comes up to meet it.'],
  rightUpper: ['Right upper eyelid', 'Comes down to close the right eye.'],
  rightLower: ['Right lower eyelid', 'Comes up to meet it.'],
  leftBrow: ['Left eyebrow', 'Above the left eye.'],
  rightBrow: ['Right eyebrow', 'Above the right eye.'],
  nose: ['Nose', 'It scrunches, and it turns with the head.'],
  mouth: ['Mouth', 'The lips. They open, smile, widen and pucker.'],
  cavity: ['Mouth cavity', 'The inside of the mouth, when it is drawn separately.'],
  teeth: ['Upper teeth', 'The top row, shown when the mouth opens.'],
  teethLower: ['Lower teeth', 'The bottom row. Optional: it shows on the same movement, a little later.'],
  tongue: ['Tongue', 'The body of it, inside the mouth. Shown when the mouth opens, and it can move on its own.'],
  tongueTip: ['Tongue tip', 'The part that comes out over the lower lip. Optional, and drawn in front of the lips.'],
  jaw: ['Jaw', 'The lower face, which drops when the mouth opens.'],
  leftEar: ['Left ear', 'It wiggles.'],
  rightEar: ['Right ear', 'It wiggles.'],
  hair: ['Hair', 'The fringe. It sways and lifts.'],
  hairTop: ['Hair on top', 'The volume above the skull.'],
  hairBack: ['Hair behind', 'What shows behind the head.'],
  facialHair: ['Facial hair', 'A beard, a moustache, a goatee. Carried by the jaw under it.'],
  element: ['Accessory', 'Glasses, a hat, anything the face wears. No movement of its own.'],
  hand: ['Hand', 'A floating hand.']
});

/** The parts the vocabulary covers, in the order a face is read. */
const PART_ORDER = Object.freeze(['head', 'eyes', 'gaze', 'eyelids', 'eyebrows', 'nose', 'mouth', 'tongue', 'jaw', 'ears', 'hair', 'facialHair', 'accessory']);

const words = (role) => ROLE_WORDS[role] || [role, ''];

/**
 * Every assignable role: which part owns it, what it is called, and whether the
 * part needs it before it can move.
 *
 * The two hands are left out on purpose. A hand is not a face part and is not
 * assigned this way — it is drawn as a pair from Design ▸ Hands, and giving it
 * a row here would offer an author a way to half-make one
 * (docs/HAND_RIGGING.md).
 *
 * @returns {{id,part,role,label,hint,partLabel,required,optional}[]}
 */
export const FACE_ROLE_VOCABULARY = Object.freeze(PART_ORDER.flatMap((part) => {
  const definition = SEMANTIC_PART_REGISTRY[part];
  if (!definition) return [];
  const required = new Set(requiredSemanticRoles(definition));
  return (definition.roles || []).map((role) => {
    const [label, hint] = words(role);
    return Object.freeze({
      // Unique across parts: the tongue is a role of the mouth (whether it
      // shows) *and* a part of its own (where it is), and the two are
      // different answers to "what is this drawing".
      id: `${part}.${role}`,
      part, role, label, hint,
      partLabel: definition.displayName || part,
      required: required.has(role),
      optional: !required.has(role)
    });
  });
}));

export const roleVocabularyEntry = (id) => FACE_ROLE_VOCABULARY.find((entry) => entry.id === id) || null;

/** The vocabulary grouped by part, for a `<select>` with `<optgroup>`s. */
export function roleVocabularyGroups() {
  const groups = new Map();
  for (const entry of FACE_ROLE_VOCABULARY) {
    if (!groups.has(entry.part)) groups.set(entry.part, { part: entry.part, label: entry.partLabel, roles: [] });
    groups.get(entry.part).roles.push(entry);
  }
  return [...groups.values()];
}

/**
 * Which roles one piece of artwork currently plays.
 *
 * Usually none or one. More than one is legitimate and is not a mistake to
 * report: a mouth that draws its own tongue has that shape as the mouth's
 * `tongue` role *and* as the tongue part's own, because the two answer
 * different questions (docs/FACE_CONTROL_RIG.md §12).
 *
 * @returns {{id,part,role,label,partId}[]}
 */
export function rolesOfElement(document = {}, elementId) {
  if (!elementId) return [];
  const out = [];
  for (const part of Object.values(document?.semanticParts || {})) {
    for (const [role, id] of Object.entries(part.roles || {})) {
      if (id !== elementId) continue;
      const entry = roleVocabularyEntry(`${part.type}.${role}`);
      out.push({ id: `${part.type}.${role}`, part: part.type, role, label: entry?.label || role, partId: part.id });
    }
  }
  return out;
}

/**
 * What a role is already drawn by, so a `<select>` can say so.
 *
 * An author reassigning a role wants to know they are taking it off something,
 * and the alternative — finding out after the press — is the one thing a list
 * of twenty-five roles must not do.
 *
 * @returns {Map<string, string>} role vocabulary id → element id
 */
export function rolesInUse(document = {}) {
  const used = new Map();
  for (const part of Object.values(document?.semanticParts || {})) {
    for (const [role, id] of Object.entries(part.roles || {})) {
      if (id && roleVocabularyEntry(`${part.type}.${role}`)) used.set(`${part.type}.${role}`, id);
    }
  }
  return used;
}
